#!/usr/bin/env python3
"""把 ECW 的音效 blob 转成 STM32 固件里的 C 数组（本地 I2S2 播放用）。

喇叭模块已转到 STM32 SHIELD（PB12=WS / PB13=SCK / PB15=SD，I2S2 发送），
因此音效由 STM32 本地播放，不再经过 ECW 的 I2S（那组引脚只能接收）。

用法：
    python tools/build_stm32_sounds.py

输入：ecw6700/main/assets/animal_sounds.bin（blob 格式见 build_sound_blob.py）
输出：stm32f407/main/app_sounds_data.c
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "ecw6700" / "main" / "assets" / "animal_sounds.bin"
OUT = ROOT / "stm32f407" / "main" / "app_sounds_data.c"


def main() -> None:
    data = SRC.read_bytes()
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("/* auto-generated by tools/build_stm32_sounds.py */\n")
        f.write("#include <stdint.h>\n\n")
        f.write("const unsigned char g_sounds_blob[%d] "
                "__attribute__((aligned(4))) = {\n" % len(data))
        for i in range(0, len(data), 16):
            f.write("    " + ",".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
        f.write("};\n")
        f.write("const unsigned int g_sounds_blob_size = %d;\n" % len(data))
    print("written %s (%d bytes)" % (OUT, len(data)))


if __name__ == "__main__":
    main()
