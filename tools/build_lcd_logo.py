#!/usr/bin/env python3
"""把 LOGO.png 转成 ST7789 彩色开机图：240×320 RGB565，RLE 压缩。

用法：
    python tools/build_lcd_logo.py [LOGO.png]

输出：stm32f407/main/app_lcd_logo.c
    const unsigned char g_lcd_logo_rle[]   每段 3 字节：RGB565 小端 + 计数(1..255)
    const unsigned int  g_lcd_logo_rle_size
    const uint16_t      g_lcd_logo_w/h

图片处理：alpha 合成到白底（透明背景不能变黑）、等比缩放进 240×320、
不裁切不变形、四周补白。
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

from PIL import Image

W, H = 240, 320
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "stm32f407" / "main" / "app_lcd_logo.c"


def to_rgb565(r: int, g: int, b: int) -> int:
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def build_pixels(path: Path) -> bytes:
    img = Image.open(path)
    if img.mode in ("RGBA", "LA", "P"):
        img = img.convert("RGBA")
        bg = Image.new("RGBA", img.size, (255, 255, 255, 255))
        img = Image.alpha_composite(bg, img)
    img = img.convert("RGB")

    scale = min(W / img.width, H / img.height)
    nw = max(1, round(img.width * scale))
    nh = max(1, round(img.height * scale))
    img = img.resize((nw, nh), Image.LANCZOS)

    canvas = Image.new("RGB", (W, H), (255, 255, 255))
    canvas.paste(img, ((W - nw) // 2, (H - nh) // 2))

    out = bytearray(W * H * 2)
    px = canvas.load()
    i = 0
    for y in range(H):
        for x in range(W):
            v = to_rgb565(*px[x, y])
            out[i] = v & 0xFF
            out[i + 1] = v >> 8
            i += 2
    return bytes(out)


def rle_encode(raw: bytes) -> bytes:
    """RGB565 流 -> (color_lo, color_hi, count) 重复段。"""
    out = bytearray()
    n = len(raw) // 2
    i = 0
    while i < n:
        color = raw[i * 2] | (raw[i * 2 + 1] << 8)
        run = 1
        while (i + run < n and run < 255 and
               (raw[(i + run) * 2] | (raw[(i + run) * 2 + 1] << 8)) == color):
            run += 1
        out += struct.pack("<HB", color, run)
        i += run
    return bytes(out)


def write_c(rle: bytes) -> None:
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("/* auto-generated by tools/build_lcd_logo.py */\n")
        f.write("#include <stdint.h>\n\n")
        f.write("const unsigned int g_lcd_logo_rle_size = %d;\n" % len(rle))
        f.write("const uint16_t g_lcd_logo_w = %d;\n" % W)
        f.write("const uint16_t g_lcd_logo_h = %d;\n\n" % H)
        f.write("const unsigned char g_lcd_logo_rle[%d] = {\n" % len(rle))
        for i in range(0, len(rle), 16):
            f.write("    " + ",".join("0x%02x" % b for b in rle[i:i + 16]) + ",\n")
        f.write("};\n")


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "LOGO.png"
    raw = build_pixels(src)
    rle = rle_encode(raw)
    write_c(rle)
    print("source : %s" % src)
    print("pixels : %dx%d RGB565 raw=%d bytes" % (W, H, len(raw)))
    print("rle    : %d bytes (%.1f%% of raw)" % (len(rle), 100.0 * len(rle) / len(raw)))
    print("c file : %s" % OUT)


if __name__ == "__main__":
    main()
